export function iconMarkup(name: string, attributes = ""): string {
  const paths = Object.hasOwn(iconPaths, name) ? iconPaths[name] : undefined;
  if (!paths) throw new Error(`Unknown icon "${name}" in the page HTML`);
  const ownClass = attributes.match(/\bclass="([^"]*)"/)?.[1];
  const rest = attributes.replace(/\s*\bdata-icon="[a-z0-9-]+"/, "").replace(/\s*\bclass="[^"]*"/, "").trim();
  const classes = ["icon", `icon-${name}`, ownClass].filter(Boolean).join(" ");
  return `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" class="${classes}"${rest ? ` ${rest}` : ""}>${paths}</svg>`;
}

export function iconNames(html: string): string[] {
  return [...html.matchAll(/<i\b[^>]*\bdata-icon="([a-z0-9-]+)"[^>]*>/g)].map((match) => match[1] as string);
}

export function inlineIcons(html: string): string {
  return html.replace(/<i\b([^>]*)>\s*<\/i\s*>/g, (whole, attributes: string) => {
    const name = attributes.match(/\bdata-icon="([a-z0-9-]+)"/)?.[1];
    return name ? iconMarkup(name, attributes) : whole;
  });
}

export function renderIcons(root: ParentNode = document): void {
  for (const placeholder of root.querySelectorAll<HTMLElement>("i[data-icon]")) {
    const attributes = [...placeholder.attributes].map(({ name, value }) => ` ${name}="${value}"`).join("");
    placeholder.outerHTML = iconMarkup(placeholder.dataset.icon ?? "", attributes);
  }
}
